-- QuazarTech schema for Supabase (Postgres)
-- Run this ONCE in the Supabase dashboard: SQL Editor -> New query -> paste -> Run.
-- It is safe to re-run (everything is "if not exists").

create table if not exists users (
  id            integer generated by default as identity primary key,
  username      text not null,
  email         text not null,
  password_hash text not null,
  phone         text,
  first_name    text,
  middle_name   text,
  last_name     text,
  suffix        text,
  full_name     text,
  role          text not null default 'user' check (role in ('user', 'admin')),
  is_verified   boolean not null default false,
  created_at    timestamptz not null default now()
);
alter table users
  add column if not exists first_name text,
  add column if not exists middle_name text,
  add column if not exists last_name text,
  add column if not exists suffix text,
  add column if not exists full_name text;
alter table users drop constraint if exists users_role_check;
alter table users add constraint users_role_check check (role in ('user', 'admin', 'rider'));
create unique index if not exists users_username_key on users (lower(username));
create unique index if not exists users_email_key    on users (lower(email));

create table if not exists riders (
  user_id          integer primary key references users(id) on delete cascade,
  vehicle_type     text not null check (vehicle_type in ('motorcycle', 'bicycle', 'car', 'van')),
  plate_number     text,
  rider_status     text not null check (rider_status in ('pending', 'approved', 'rejected')),
  rider_applied_at timestamptz not null default now()
);
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'users' and column_name = 'rider_status'
  ) then
    execute $migration$
      insert into riders (user_id, vehicle_type, plate_number, rider_status, rider_applied_at)
      select id, vehicle_type, plate_number, rider_status, COALESCE(rider_applied_at, now())
      from users
      where rider_status in ('pending', 'approved', 'rejected')
        and vehicle_type in ('motorcycle', 'bicycle', 'car', 'van')
      on conflict (user_id) do update
      set vehicle_type = excluded.vehicle_type,
          plate_number = excluded.plate_number,
          rider_status = excluded.rider_status,
          rider_applied_at = excluded.rider_applied_at
    $migration$;
    alter table users drop column rider_status;
    alter table users drop column vehicle_type;
    alter table users drop column plate_number;
    alter table users drop column rider_applied_at;
  end if;
end $$;

create table if not exists categories (
  id   integer generated by default as identity primary key,
  name text not null unique,
  slug text not null unique
);

create table if not exists products (
  id           integer generated by default as identity primary key,
  category_id  integer not null references categories(id),
  name         text not null,
  slug         text not null unique,
  brand        text,
  description  text,
  price        numeric(12,2) not null check (price >= 0),
  stock        integer not null default 0 check (stock >= 0),
  image        text,
  members_only boolean not null default false,
  is_featured  boolean not null default false,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now()
);
create index if not exists idx_products_category on products (category_id);

create table if not exists promo_codes (
  id               integer generated by default as identity primary key,
  code             text not null,
  discount_percent integer not null check (discount_percent between 1 and 100),
  expires_at       timestamptz,
  is_active        boolean not null default true
);
create unique index if not exists promo_codes_code_key on promo_codes (lower(code));

create table if not exists cart_items (
  id         integer generated by default as identity primary key,
  user_id    integer not null references users(id) on delete cascade,
  product_id integer not null references products(id) on delete cascade,
  quantity   integer not null default 1 check (quantity > 0),
  added_at   timestamptz not null default now(),
  unique (user_id, product_id)
);

create table if not exists orders (
  id               integer generated by default as identity primary key,
  user_id          integer not null references users(id),
  promo_code_id    integer references promo_codes(id),
  status           text not null default 'pending' check (status in ('pending', 'approved', 'shipped', 'delivered', 'declined')),
  payment_status   text not null default 'unpaid',
  shipped_at       timestamptz,
  delivered_at     timestamptz,
  paid_at          timestamptz,
  proof_image      text,
  rider_id         integer references users(id),
  rider_name       text,
  estimated_delivery date,
  assigned_at      timestamptz,
  assigned_by      integer references users(id),
  failed_at        timestamptz,
  failure_reason   text,
  subtotal         numeric(12,2) not null check (subtotal >= 0),
  discount_amount  numeric(12,2) not null default 0 check (discount_amount >= 0),
  total            numeric(12,2) not null check (total >= 0),
  payment_method   text,
  shipping_name    text not null,
  shipping_phone   text not null,
  shipping_address text not null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz
);
alter table orders add column if not exists payment_status text not null default 'unpaid';
alter table orders add column if not exists shipped_at timestamptz;
alter table orders add column if not exists delivered_at timestamptz;
alter table orders add column if not exists paid_at timestamptz;
alter table orders add column if not exists proof_image text;
alter table orders add column if not exists rider_id integer references users(id);
alter table orders add column if not exists rider_name text;
alter table orders add column if not exists estimated_delivery date;
alter table orders add column if not exists assigned_at timestamptz;
alter table orders add column if not exists assigned_by integer references users(id);
alter table orders add column if not exists failed_at timestamptz;
alter table orders add column if not exists failure_reason text;
alter table orders drop constraint if exists orders_status_check;
alter table orders add constraint orders_status_check
  check (status in ('pending', 'approved', 'shipped', 'delivered', 'declined'));
create index if not exists idx_orders_user on orders (user_id);

create table if not exists order_items (
  id         integer generated by default as identity primary key,
  order_id   integer not null references orders(id) on delete cascade,
  product_id integer not null references products(id),
  quantity   integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0)
);
create index if not exists idx_order_items_order on order_items (order_id);

create table if not exists otp_codes (
  id         integer generated by default as identity primary key,
  user_id    integer not null references users(id) on delete cascade,
  code       text not null,
  attempts   integer not null default 0,
  used       boolean not null default false,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_otp_user on otp_codes (user_id);

create table if not exists reviews (
  id         integer generated by default as identity primary key,
  product_id integer not null references products(id) on delete cascade,
  user_id    integer not null references users(id) on delete cascade,
  rating     integer not null check (rating between 1 and 5),
  comment    text,
  created_at timestamptz not null default now(),
  unique (product_id, user_id)
);
create index if not exists idx_reviews_product on reviews (product_id);

create table if not exists review_replies (
  id         integer generated by default as identity primary key,
  review_id  integer not null references reviews(id) on delete cascade,
  user_id    integer not null references users(id) on delete cascade,
  comment    text not null,
  created_at timestamptz not null default now()
);
create index if not exists idx_replies_review on review_replies (review_id);

-- SECURITY: Supabase publishes every table in "public" through its REST API using
-- the public anon key. This site talks to the database only through its own Express
-- server (direct Postgres connection), so lock the REST API out completely:
-- RLS on + no policies = anon/authenticated roles can read and write nothing.
-- (The server's "postgres" role bypasses RLS, so the site keeps working.)
alter table users           enable row level security;
alter table categories      enable row level security;
alter table products        enable row level security;
alter table promo_codes     enable row level security;
alter table cart_items      enable row level security;
alter table orders          enable row level security;
alter table order_items     enable row level security;
alter table otp_codes       enable row level security;
alter table reviews         enable row level security;
alter table review_replies  enable row level security;
